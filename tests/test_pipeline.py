"""End-to-end check of the download + ffmpeg conversion pipeline.

YouTube itself isn't contacted: a short clip generated by ffmpeg is served from a
local HTTP server and fetched through yt-dlp's generic extractor, which exercises
the same download, merge and conversion code paths.
"""

import functools
import http.server
import os
import shutil
import subprocess
import threading
from pathlib import Path

import pytest

from app import formats, ytdl

pytestmark = pytest.mark.skipif(not shutil.which("ffmpeg"), reason="ffmpeg not installed")


@pytest.fixture(scope="module")
def media_server(tmp_path_factory):
    root = tmp_path_factory.mktemp("media")
    subprocess.run(
        [
            "ffmpeg", "-loglevel", "error", "-y",
            "-f", "lavfi", "-i", "testsrc2=size=640x360:rate=25:duration=3",
            "-f", "lavfi", "-i", "sine=frequency=440:duration=3",
            "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest",
            str(root / "clip.mp4"),
        ],
        check=True,
    )
    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(root))
    handler.log_message = lambda *a, **k: None
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    os.environ["NO_PROXY"] = os.environ["no_proxy"] = "127.0.0.1,localhost"
    yield f"http://127.0.0.1:{server.server_address[1]}/clip.mp4"
    server.shutdown()


def _probe(path: Path) -> str:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "stream=codec_name", "-of", "csv=p=0", str(path)],
        capture_output=True, text=True, check=True,
    )
    return out.stdout


@pytest.mark.parametrize(
    "fmt,bitrate,ext,codec",
    [
        ("mp3", 320, ".mp3", "mp3"),
        ("m4a", 256, ".m4a", "aac"),
        ("opus", 160, ".opus", "opus"),
        ("ogg", 192, ".ogg", "vorbis"),
        ("wav", None, ".wav", "pcm_s16le"),
        ("flac", None, ".flac", "flac"),
    ],
)
def test_audio_conversion(media_server, tmp_path, fmt, bitrate, ext, codec):
    pps, thumb = formats.postprocessors("audio", None, fmt, bitrate, embed=True)
    events = []
    path = ytdl.download(
        media_server, tmp_path, format_spec="ba/b", format_sort=[], postprocessors=pps,
        write_thumbnail=thumb, merge_format=None, expected_size=None, on_progress=events.append,
    )
    assert path.suffix == ext
    assert codec in _probe(path)
    assert any(e["stage"] == "downloading" for e in events)
    assert any(e["stage"] == "processing" for e in events)


@pytest.mark.parametrize("container", ["mp4", "mkv"])
def test_video_remux(media_server, tmp_path, container):
    pps, _ = formats.postprocessors("video", container, None, None, embed=True)
    path = ytdl.download(
        media_server, tmp_path, format_spec="bv*+ba/b", format_sort=["res:360"], postprocessors=pps,
        write_thumbnail=False, merge_format=container, expected_size=None, on_progress=lambda e: None,
    )
    assert path.suffix == f".{container}"
    assert "h264" in _probe(path)


def test_cancel(media_server, tmp_path):
    with pytest.raises(ytdl.FetchError):
        ytdl.download(
            media_server, tmp_path, format_spec="b", format_sort=[], postprocessors=[],
            write_thumbnail=False, merge_format=None, expected_size=None, on_progress=lambda e: None,
            is_cancelled=lambda: True,
        )
